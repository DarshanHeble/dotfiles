#!/usr/bin/env python3
"""
Omarchy-style Theme Hook: 10-terminals.py
Generates terminal theme files (Foot, Alacritty, Ghostty, Kitty)
from the active Caelestia Material 3 scheme and retints running terminals.
"""

import os
import sys
import json
from pathlib import Path

def get_current_scheme():
    # 1. Try environment variable from Caelestia postHook
    env_colours = os.environ.get("SCHEME_COLOURS")
    if env_colours:
        try:
            colours = json.loads(env_colours)
            name = os.environ.get("SCHEME_NAME", "default")
            mode = os.environ.get("SCHEME_MODE", "dark")
            return name, mode, colours
        except Exception:
            pass

    # 2. Try ~/.local/state/caelestia/scheme.json
    state_file = Path.home() / ".local/state/caelestia/scheme.json"
    if state_file.exists():
        try:
            data = json.loads(state_file.read_text())
            return data.get("name", "default"), data.get("mode", "dark"), data.get("colours", {})
        except Exception:
            pass

    # 3. Fallback to querying caelestia
    try:
        from caelestia.utils.scheme import get_scheme
        s = get_scheme()
        return s.name, s.mode, s.colours
    except Exception as e:
        print(f"Error fetching scheme: {e}", file=sys.stderr)
        sys.exit(1)

def main():
    scheme_name, mode, cols = get_current_scheme()

    # Helper color accessors
    def c(key, fallback="ffffff"):
        val = cols.get(key, fallback)
        return val.lstrip("#")

    def ch(key, fallback="ffffff"):
        return f"#{c(key, fallback)}"

    # ANSI terminal colors (term0 to term15)
    term = [c(f"term{i}", "888888") for i in range(16)]
    term_hash = [f"#{t}" for t in term]

    # Directories
    theme_current_dir = Path.home() / ".config/theme/current"
    omarchy_theme_dir = Path.home() / ".local/state/omarchy/current/theme"
    theme_current_dir.mkdir(parents=True, exist_ok=True)
    omarchy_theme_dir.mkdir(parents=True, exist_ok=True)

    bg = c("background", "131317" if mode == "dark" else "f8f9fc")
    fg = c("onSurface", "e5e1e7" if mode == "dark" else "191c1e")
    primary = c("primary", "c2c1ff")
    cursor = c("primary", "c2c1ff")
    sel_bg = c("secondaryContainer", "4c6170")
    sel_fg = c("onSecondaryContainer", "ffffff")

    # -------------------------------------------------------------
    # 1. Foot Theme (~/.config/foot/theme.ini)
    # -------------------------------------------------------------
    foot_colors = f"""background={bg}
foreground={fg}

regular0={term[0]}
regular1={term[1]}
regular2={term[2]}
regular3={term[3]}
regular4={term[4]}
regular5={term[5]}
regular6={term[6]}
regular7={term[7]}

bright0={term[8]}
bright1={term[9]}
bright2={term[10]}
bright3={term[11]}
bright4={term[12]}
bright5={term[13]}
bright6={term[14]}
bright7={term[15]}

selection-background={sel_bg}
selection-foreground={sel_fg}"""

    foot_content = f"""# Generated by Omarchy Theme Engine from {scheme_name} ({mode})
[colors-dark]
{foot_colors}

[colors-light]
{foot_colors}
"""
    (theme_current_dir / "foot.ini").write_text(foot_content)
    foot_config_dest = Path.home() / ".config/foot/theme.ini"
    foot_config_dest.parent.mkdir(parents=True, exist_ok=True)
    foot_config_dest.write_text(foot_content)
    (omarchy_theme_dir / "foot.ini").write_text(foot_content)

    # -------------------------------------------------------------
    # 2. Alacritty Theme (~/.config/alacritty/theme.toml)
    # -------------------------------------------------------------
    alacritty_content = f"""# Generated by Omarchy Theme Engine from {scheme_name} ({mode})
[colors.primary]
background = "{ch('background', bg)}"
foreground = "{ch('onSurface', fg)}"

[colors.cursor]
text = "{ch('background', bg)}"
cursor = "{ch('primary', cursor)}"

[colors.selection]
text = "#{sel_fg}"
background = "#{sel_bg}"

[colors.normal]
black = "{term_hash[0]}"
red = "{term_hash[1]}"
green = "{term_hash[2]}"
yellow = "{term_hash[3]}"
blue = "{term_hash[4]}"
magenta = "{term_hash[5]}"
cyan = "{term_hash[6]}"
white = "{term_hash[7]}"

[colors.bright]
black = "{term_hash[8]}"
red = "{term_hash[9]}"
green = "{term_hash[10]}"
yellow = "{term_hash[11]}"
blue = "{term_hash[12]}"
magenta = "{term_hash[13]}"
cyan = "{term_hash[14]}"
white = "{term_hash[15]}"
"""
    (theme_current_dir / "alacritty.toml").write_text(alacritty_content)
    alacritty_dest = Path.home() / ".config/alacritty/theme.toml"
    alacritty_dest.parent.mkdir(parents=True, exist_ok=True)
    alacritty_dest.write_text(alacritty_content)
    (omarchy_theme_dir / "alacritty.toml").write_text(alacritty_content)

    # -------------------------------------------------------------
    # 3. Ghostty Theme (~/.config/ghostty/theme.conf)
    # -------------------------------------------------------------
    ghostty_content = f"""# Generated by Omarchy Theme Engine from {scheme_name} ({mode})
background = #{bg}
foreground = #{fg}
cursor-color = #{cursor}
selection-background = #{sel_bg}
selection-foreground = #{sel_fg}

palette = 0={term_hash[0]}
palette = 1={term_hash[1]}
palette = 2={term_hash[2]}
palette = 3={term_hash[3]}
palette = 4={term_hash[4]}
palette = 5={term_hash[5]}
palette = 6={term_hash[6]}
palette = 7={term_hash[7]}
palette = 8={term_hash[8]}
palette = 9={term_hash[9]}
palette = 10={term_hash[10]}
palette = 11={term_hash[11]}
palette = 12={term_hash[12]}
palette = 13={term_hash[13]}
palette = 14={term_hash[14]}
palette = 15={term_hash[15]}
"""
    (theme_current_dir / "ghostty.conf").write_text(ghostty_content)
    ghostty_dest = Path.home() / ".config/ghostty/theme.conf"
    ghostty_dest.parent.mkdir(parents=True, exist_ok=True)
    ghostty_dest.write_text(ghostty_content)

    # -------------------------------------------------------------
    # 4. Kitty Theme (~/.config/kitty/theme.conf)
    # -------------------------------------------------------------
    kitty_content = f"""# Generated by Omarchy Theme Engine from {scheme_name} ({mode})
background #{bg}
foreground #{fg}
cursor #{cursor}
cursor_text_color #{bg}
selection_background #{sel_bg}
selection_foreground #{sel_fg}

color0 {term_hash[0]}
color1 {term_hash[1]}
color2 {term_hash[2]}
color3 {term_hash[3]}
color4 {term_hash[4]}
color5 {term_hash[5]}
color6 {term_hash[6]}
color7 {term_hash[7]}
color8 {term_hash[8]}
color9 {term_hash[9]}
color10 {term_hash[10]}
color11 {term_hash[11]}
color12 {term_hash[12]}
color13 {term_hash[13]}
color14 {term_hash[14]}
color15 {term_hash[15]}
"""
    (theme_current_dir / "kitty.conf").write_text(kitty_content)
    kitty_dest = Path.home() / ".config/kitty/theme.conf"
    kitty_dest.parent.mkdir(parents=True, exist_ok=True)
    kitty_dest.write_text(kitty_content)

    # -------------------------------------------------------------
    # 5. Shell Environment Variables (~/.config/theme/current/colors.sh)
    # -------------------------------------------------------------
    sh_vars = f"""# Shell color variables for {scheme_name} ({mode})
export THEME_NAME="{scheme_name}"
export THEME_MODE="{mode}"
export THEME_BG="#{bg}"
export THEME_FG="#{fg}"
export THEME_PRIMARY="#{primary}"
export THEME_TERM0="{term_hash[0]}"
export THEME_TERM1="{term_hash[1]}"
export THEME_TERM2="{term_hash[2]}"
export THEME_TERM3="{term_hash[3]}"
export THEME_TERM4="{term_hash[4]}"
export THEME_TERM5="{term_hash[5]}"
export THEME_TERM6="{term_hash[6]}"
export THEME_TERM7="{term_hash[7]}"
export THEME_TERM8="{term_hash[8]}"
export THEME_TERM9="{term_hash[9]}"
export THEME_TERM10="{term_hash[10]}"
export THEME_TERM11="{term_hash[11]}"
export THEME_TERM12="{term_hash[12]}"
export THEME_TERM13="{term_hash[13]}"
export THEME_TERM14="{term_hash[14]}"
export THEME_TERM15="{term_hash[15]}"
"""
    (theme_current_dir / "colors.sh").write_text(sh_vars)
    (theme_current_dir / "colors.json").write_text(json.dumps(cols, indent=2))

    # -------------------------------------------------------------
    # 6. Live Broadcast OSC Escape Sequences to Active Terminals
    # -------------------------------------------------------------
    def to_rgb_osc(code, hex_color):
        h = hex_color.lstrip("#")
        return f"\033]{code};rgb:{h[0:2]}/{h[2:4]}/{h[4:6]}\007"

    osc = ""
    osc += to_rgb_osc(10, fg)
    osc += to_rgb_osc(11, bg)
    osc += to_rgb_osc(12, cursor)
    osc += to_rgb_osc(17, sel_bg)
    for i in range(16):
        osc += to_rgb_osc(f"4;{i}", term[i])

    pts_dir = Path("/dev/pts")
    if pts_dir.is_dir():
        for pt in pts_dir.iterdir():
            if pt.name.isdigit():
                try:
                    fd = os.open(str(pt), os.O_WRONLY | os.O_NONBLOCK | os.O_NOCTTY)
                    try:
                        os.write(fd, osc.encode())
                    finally:
                        os.close(fd)
                except Exception:
                    pass

    # Signal kitty if running
    os.system("killall -SIGUSR1 kitty 2>/dev/null || true")

    print(f"✓ Terminal themes updated for '{scheme_name}' ({mode})")

if __name__ == "__main__":
    main()
