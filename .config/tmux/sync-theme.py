#!/usr/bin/env python3
"""
Sync Caelestia / Material 3 dynamic palette into Tmux.
Reads ~/.config/hypr/scheme/current.lua and generates ~/.config/tmux/theme.conf,
then reloads the active tmux server if running.
"""

import os
import subprocess
import re

SCHEME_FILE = os.path.expanduser("~/.config/hypr/scheme/current.lua")
TMUX_THEME_FILE = os.path.expanduser("~/.config/tmux/theme.conf")

def parse_scheme(path):
    colors = {}
    if not os.path.exists(path):
        return colors
    with open(path, "r") as f:
        content = f.read()
    matches = re.findall(r'([a-zA-Z0-9_]+)\s*=\s*"#?([a-fA-F0-9]{6})"', content)
    for k, v in matches:
        colors[k] = f"#{v}"
    return colors

def main():
    scheme = parse_scheme(SCHEME_FILE)
    if not scheme:
        return

    # Extract primary, accent, surface, and text colors
    primary = scheme.get("primaryFixed") or scheme.get("primary") or "#bfedd0"
    on_primary = scheme.get("onPrimaryFixed") or scheme.get("onPrimary") or "#1d4732"
    secondary = scheme.get("secondaryFixed") or scheme.get("secondary") or "#d0e8d7"
    surface = scheme.get("surfaceContainer") or scheme.get("surface") or "#040705"
    surface_high = scheme.get("surfaceContainerHighest") or scheme.get("outlineVariant") or "#070c09"
    text = scheme.get("text") or scheme.get("onSurface") or "#dee8df"
    subtext = scheme.get("subtext0") or scheme.get("onSurfaceVariant") or "#6e7870"
    accent = scheme.get("tertiaryFixed") or scheme.get("tertiary") or "#bdf8fc"
    error = scheme.get("error") or "#fa746f"

    tmux_conf = f"""# Caelestia dynamic Material 3 palette for Tmux
# Auto-generated by ~/.config/tmux/sync-theme.py

set -g status-style "bg=default,fg={text}"

# Session widget in top-left
set -g status-left-length 30
set -g status-left "#[fg={on_primary},bg={primary},bold] #S #[bg=default] "

# Status widgets in top-right
set -g status-right-length 50
set -g status-right "#[fg={error}]#{{?pane_in_mode,COPY ,}}#[fg={accent}]#{{?client_prefix,PREFIX ,}}#[fg={secondary}]#{{?window_zoomed_flag,ZOOM ,}}#[fg={subtext}]#h "

# Window tabs
set -g window-status-separator ""
set -g window-status-format "#[fg={subtext}] #I:#W "
set -g window-status-current-format "#[fg={primary},bold] #I:#W "

# Borders
set -g pane-border-style "fg={surface_high}"
set -g pane-active-border-style "fg={primary}"

# Popups & command messages
set -g message-style "bg={surface},fg={primary}"
set -g message-command-style "bg={surface},fg={primary}"
set -g mode-style "bg={primary},fg={on_primary}"
setw -g clock-mode-colour "{primary}"
"""

    os.makedirs(os.path.dirname(TMUX_THEME_FILE), exist_ok=True)
    with open(TMUX_THEME_FILE, "w") as f:
        f.write(tmux_conf)

    # Reload active tmux server if running
    try:
        subprocess.run(["tmux", "source-file", TMUX_THEME_FILE], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    except Exception:
        pass

if __name__ == "__main__":
    main()
